"""Build the compact IP-to-country index used by the playlist splitter.

The index is derived from the free DB-IP "IP to Country Lite" database
(https://db-ip.com, CC BY 4.0) as republished by the ip-location-db project.
Each range is reduced to its first address and its country code; the next
range's first address marks the end of the previous range, so lookups need
only one binary search over a sorted list of start addresses.

Adresses that DB-IP does not cover (private, reserved, multicast space) are
simply absent from the index and fall back to the unknown country at lookup
time.

Usage (needs only the Python standard library):

    curl -sSL -o ip-location-db.tgz \\
        https://codeload.github.com/sapics/ip-location-db/tar.gz/refs/heads/main
    mkdir -p ip-location-db
    tar xzf ip-location-db.tgz -C ip-location-db --strip-components=1 \\
        ip-location-db-main/dbip-country
    python tools/build_country_index.py \\
        --dbip-dir ip-location-db/dbip-country --snapshot 2026-06-01

The checked-in index in the repository was built from the DB-IP snapshot of
2026-06-01 (the version published as @ip-location-db/dbip-country 2.3.2026060120).
"""

import argparse
import gzip
import ipaddress
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSET_DIR = ROOT / 'src' / 'data'
LICENSE_SOURCE = 'https://db-ip.com'

HEADER = (
    '# IP-to-country index generated by tools/build_country_index.py.\n'
    '# Data: DB-IP IP to Country Lite ({snapshot}), licensed CC BY 4.0.\n'
    '# Attribution: IP Geolocation by DB-IP <https://db-ip.com>\n'
    '# Format: one "start-address<TAB>country-code" line per range, sorted.\n'
)


def read_ranges(csv_path, version):
    """Yield (first address, country) for every range in a DB-IP CSV."""
    address = ipaddress.IPv6Address if version == 6 else ipaddress.IPv4Address
    with open(csv_path, encoding='utf-8') as source:
        for line in source:
            start, end, country = line.rstrip('\n').split(',')
            yield int(address(start)), country


def build(csv_paths, snapshot):
    """Compress one sorted "start<TAB>country" table per IP version."""
    payload = {}
    for version, csv_path in zip((4, 6), csv_paths):
        ranges = sorted(read_ranges(csv_path, version))
        table = ''.join(f'{start}\t{country}\n' for start, country in ranges)
        payload[version] = gzip.compress(table.encode('utf-8'), mtime=0)
        print(f'IPv{version}: {len(ranges)} ranges, {len(payload[version]) / 1e6:.2f} MiB')
    return payload


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--dbip-dir', required=True, type=Path,
                        help='folder holding dbip-country-ipv4.csv and dbip-country-ipv6.csv')
    parser.add_argument('--snapshot', default='latest', help='snapshot label written into the header')
    parser.add_argument('--out-dir', default=ASSET_DIR, type=Path)
    args = parser.parse_args()

    payload = build(
        [args.dbip_dir / 'dbip-country-ipv4.csv', args.dbip_dir / 'dbip-country-ipv6.csv'],
        args.snapshot,
    )
    args.out_dir.mkdir(parents=True, exist_ok=True)
    header = HEADER.format(snapshot=args.snapshot).encode('utf-8')
    for version, data in payload.items():
        target = args.out_dir / f'ip2country-v{version}.tsv.gz'
        # Concatenated members are valid gzip; the header stays readable with
        # `zcat`, which matters when auditing attribution.
        with open(target, 'wb') as out:
            out.write(gzip.compress(header, mtime=0))
            out.write(data)
        print(f'wrote {target.relative_to(ROOT) if target.is_relative_to(ROOT) else target} '
              f'({os.path.getsize(target) / 1e6:.2f} MiB)')


if __name__ == '__main__':
    main()
